"""Multiplicative POD/random coarse-space inverse actions for Stage 5."""

from __future__ import annotations

from dataclasses import dataclass
from time import perf_counter
from typing import Tuple

import numpy as np
import scipy.linalg as la
import scipy.sparse as sp

from .preconditioners import InverseAction, PreconditionerFailure


@dataclass(frozen=True)
class AZPetrovFactors:
    r"""Factors for the trial/test pair generated by ``AZ=WR``.

    ``trial`` is the orthonormal right/correction space ``Z``; ``test`` is
    the orthonormal residual space ``W``; ``triangular`` is ``R``; and
    ``recycling_trial`` is ``U=Z R^{-1}``, formed by triangular solves.
    """

    trial: np.ndarray
    test: np.ndarray
    triangular: np.ndarray
    recycling_trial: np.ndarray
    diagnostics: dict


def _validated_orthonormal_basis(matrix: sp.spmatrix, basis: np.ndarray) -> Tuple[np.ndarray, float]:
    basis = np.asarray(basis, dtype=float)
    if basis.ndim != 2 or basis.shape[0] != matrix.shape[0]:
        raise ValueError("coarse basis has incompatible dimensions")
    error = float(np.linalg.norm(basis.T @ basis - np.eye(basis.shape[1])))
    if error > 1.0e-8:
        raise ValueError(f"coarse basis must be orthonormal (error={error:.3e})")
    return basis, error


def factor_az_petrov(
    matrix: sp.spmatrix,
    basis: np.ndarray,
    condition_limit: float = 1.0e14,
) -> AZPetrovFactors:
    r"""Factor ``AZ=WR`` and form ``U=Z R^{-1}`` without an inverse."""

    start = perf_counter()
    basis, orthogonality_error = _validated_orthonormal_basis(matrix, basis)
    az_start = perf_counter()
    matrix_basis = np.asarray(matrix @ basis, dtype=float)
    az_seconds = perf_counter() - az_start
    qr_start = perf_counter()
    test, triangular = la.qr(matrix_basis, mode="economic")
    qr_seconds = perf_counter() - qr_start
    condition = float(np.linalg.cond(triangular))
    if not np.isfinite(condition) or condition > condition_limit:
        raise PreconditionerFailure(
            f"AZ Petrov factor is unstable (cond={condition:.3e})"
        )
    recycling_start = perf_counter()
    recycling_trial = la.solve_triangular(
        triangular.T, basis.T, lower=True
    ).T
    recycling_seconds = perf_counter() - recycling_start
    test_orthogonality_error = float(
        np.linalg.norm(test.T @ test - np.eye(test.shape[1]))
    )
    coupling_identity_error = float(
        np.linalg.norm(test.T @ matrix_basis - triangular)
        / max(np.linalg.norm(triangular), np.finfo(float).tiny)
    )
    au_identity_error = float(
        np.linalg.norm(np.asarray(matrix @ recycling_trial) - test)
        / max(np.linalg.norm(test), np.finfo(float).tiny)
    )
    diagnostics = {
        "coarse_dimension": int(basis.shape[1]),
        "basis_orthogonality_error": orthogonality_error,
        "test_orthogonality_error": test_orthogonality_error,
        "reduced_condition": condition,
        "wtaz_condition": condition,
        "wtaz_equals_r_relative_error": coupling_identity_error,
        "au_equals_w_relative_error": au_identity_error,
        "az_seconds": az_seconds,
        "qr_seconds": qr_seconds,
        "recycling_normalization_seconds": recycling_seconds,
        "petrov_setup_seconds": az_seconds + qr_seconds,
        "recycling_setup_seconds": perf_counter() - start,
    }
    return AZPetrovFactors(
        trial=basis,
        test=test,
        triangular=triangular,
        recycling_trial=recycling_trial,
        diagnostics=diagnostics,
    )


def build_galerkin_coarse_preconditioner(
    matrix: sp.spmatrix,
    base: InverseAction,
    basis: np.ndarray,
    name: str = "galerkin",
) -> Tuple[InverseAction, dict]:
    r"""Build the counterfactual symmetric-style ``Z(Z^TAZ)^{-1}Z^T`` action."""

    start = perf_counter()
    basis, orthogonality_error = _validated_orthonormal_basis(matrix, basis)
    matrix_basis = np.asarray(matrix @ basis, dtype=float)
    reduced = basis.T @ matrix_basis
    condition = float(np.linalg.cond(reduced))
    try:
        lu, pivots = la.lu_factor(reduced)
    except la.LinAlgError as exc:
        raise PreconditionerFailure(
            f"Galerkin reduced factorization failed: {exc}"
        ) from exc
    setup_seconds = perf_counter() - start

    def combined(residual: np.ndarray) -> np.ndarray:
        classical = base.apply(residual)
        remaining = residual - matrix @ classical
        coefficients = la.lu_solve((lu, pivots), basis.T @ remaining)
        return classical + basis @ coefficients

    diagnostics = {
        "coarse_variant": "galerkin_counterfactual",
        "coarse_dimension": int(basis.shape[1]),
        "coarse_setup_seconds": setup_seconds,
        "reduced_condition": condition,
        "ztaz_condition": condition,
        "basis_orthogonality_error": orthogonality_error,
    }
    return (
        InverseAction(
            f"{base.name}+{name}_q{basis.shape[1]}",
            combined,
            setup_seconds=base.setup_seconds + setup_seconds,
            diagnostics=diagnostics,
        ),
        diagnostics,
    )


def build_az_petrov_coarse_preconditioner(
    matrix: sp.spmatrix,
    base: InverseAction,
    factors: AZPetrovFactors,
    recycling: bool = False,
    name: str = "az_petrov",
) -> Tuple[InverseAction, dict]:
    r"""Build Petrov or algebraically equivalent recycling correction.

    Petrov uses ``Z solve(R, W^T s)``.  Recycling uses ``U W^T s`` with
    ``U=Z R^{-1}``.  Both are inserted after the classical correction with
    ``s=(I-AM^{-1})r``.
    """

    if factors.trial.shape[0] != matrix.shape[0]:
        raise ValueError("Petrov factors have incompatible dimensions")

    def combined(residual: np.ndarray) -> np.ndarray:
        classical = base.apply(residual)
        remaining = residual - matrix @ classical
        projected = factors.test.T @ remaining
        if recycling:
            correction = factors.recycling_trial @ projected
        else:
            coefficients = la.solve_triangular(factors.triangular, projected)
            correction = factors.trial @ coefficients
        return classical + correction

    diagnostics = dict(factors.diagnostics)
    diagnostics.update(
        {
            "coarse_variant": "recycling_normalized" if recycling else "az_petrov",
            "coarse_setup_seconds": factors.diagnostics[
                "recycling_setup_seconds" if recycling else "petrov_setup_seconds"
            ],
        }
    )
    return (
        InverseAction(
            f"{base.name}+{name}_q{factors.trial.shape[1]}",
            combined,
            setup_seconds=base.setup_seconds + diagnostics["coarse_setup_seconds"],
            diagnostics=diagnostics,
        ),
        diagnostics,
    )


def build_paired_petrov_coarse_preconditioner(
    matrix: sp.spmatrix,
    base: InverseAction,
    trial_basis: np.ndarray,
    test_basis: np.ndarray,
    name: str = "paired_petrov",
) -> Tuple[InverseAction, dict]:
    r"""Build ``Z(W^TAZ)^{-1}W^T`` for a supplied orthonormal pair."""

    start = perf_counter()
    trial_basis, trial_error = _validated_orthonormal_basis(matrix, trial_basis)
    test_basis, test_error = _validated_orthonormal_basis(matrix, test_basis)
    if trial_basis.shape[1] != test_basis.shape[1]:
        raise ValueError("trial and test spaces must have the same dimension")
    reduced = test_basis.T @ np.asarray(matrix @ trial_basis, dtype=float)
    condition = float(np.linalg.cond(reduced))
    try:
        lu, pivots = la.lu_factor(reduced)
    except la.LinAlgError as exc:
        raise PreconditionerFailure(
            f"paired Petrov reduced factorization failed: {exc}"
        ) from exc
    setup_seconds = perf_counter() - start

    def combined(residual: np.ndarray) -> np.ndarray:
        classical = base.apply(residual)
        remaining = residual - matrix @ classical
        coefficients = la.lu_solve((lu, pivots), test_basis.T @ remaining)
        return classical + trial_basis @ coefficients

    diagnostics = {
        "coarse_variant": "paired_petrov",
        "coarse_dimension": int(trial_basis.shape[1]),
        "coarse_setup_seconds": setup_seconds,
        "reduced_condition": condition,
        "wtaz_condition": condition,
        "basis_orthogonality_error": trial_error,
        "test_orthogonality_error": test_error,
    }
    return (
        InverseAction(
            f"{base.name}+{name}_q{trial_basis.shape[1]}",
            combined,
            setup_seconds=base.setup_seconds + setup_seconds,
            diagnostics=diagnostics,
        ),
        diagnostics,
    )


def sparse_symmetry_measure(matrix: sp.spmatrix) -> float:
    """Return ``||A-A^T||_F/||A||_F`` without densifying ``A``."""

    norm = float(sp.linalg.norm(matrix))
    return float(sp.linalg.norm(matrix - matrix.T) / norm) if norm > 0.0 else 0.0


def random_orthonormal_basis(n: int, q: int, seed: int) -> np.ndarray:
    """Create the random-q-dimensional control subspace used in Stage 5."""

    if not 0 < q <= n:
        raise ValueError("q must satisfy 0 < q <= n")
    rng = np.random.default_rng(seed)
    basis, _ = np.linalg.qr(rng.normal(size=(n, q)), mode="reduced")
    return basis


def build_multiplicative_coarse_preconditioner(
    matrix: sp.spmatrix,
    base: InverseAction,
    basis: np.ndarray,
    symmetry_threshold: float = 1.0e-10,
    name: str = "pod",
) -> Tuple[InverseAction, dict]:
    r"""Build ``P(r)=M^{-1}r+C_Z(r-A M^{-1}r)`` without an explicit inverse.

    If ``||A-A^T||/||A||`` is below ``symmetry_threshold``, the Galerkin
    correction is ``C_Z(s)=Z solve(Z^T A Z, Z^T s)``.

    Otherwise, a Petrov-Galerkin minimum-residual correction is used.  With
    test space ``W=A Z``, it solves ``min_alpha ||s-AZ alpha||_2`` using a thin
    QR factorization ``AZ=QR`` and triangular solve ``R alpha=Q^T s``.  This
    avoids silently treating a nonsymmetric RBF-FD matrix as symmetric and
    avoids explicitly forming or inverting normal equations.
    """

    start = perf_counter()
    basis = np.asarray(basis, dtype=float)
    if basis.ndim != 2 or basis.shape[0] != matrix.shape[0]:
        raise ValueError("coarse basis has incompatible dimensions")
    gram = basis.T @ basis
    orthogonality_error = float(np.linalg.norm(gram - np.eye(basis.shape[1])))
    if orthogonality_error > 1.0e-8:
        raise ValueError(f"coarse basis must be orthonormal (error={orthogonality_error:.3e})")

    symmetry = sparse_symmetry_measure(matrix)
    matrix_basis = np.asarray(matrix @ basis, dtype=float)
    if symmetry <= symmetry_threshold:
        variant = "galerkin"
        reduced = basis.T @ matrix_basis
        reduced_condition = float(np.linalg.cond(reduced))
        try:
            lu, pivots = la.lu_factor(reduced)
        except la.LinAlgError as exc:
            raise PreconditionerFailure(f"Galerkin reduced factorization failed: {exc}") from exc

        def coarse_action(residual: np.ndarray) -> np.ndarray:
            coefficients = la.lu_solve((lu, pivots), basis.T @ residual)
            return basis @ coefficients

    else:
        variant = "petrov_minres"
        q_basis, triangular = la.qr(matrix_basis, mode="economic")
        reduced_condition = float(np.linalg.cond(triangular))
        if not np.isfinite(reduced_condition) or reduced_condition > 1.0e14:
            raise PreconditionerFailure(
                f"minimum-residual coarse factor is unstable (cond={reduced_condition:.3e})"
            )

        def coarse_action(residual: np.ndarray) -> np.ndarray:
            coefficients = la.solve_triangular(triangular, q_basis.T @ residual)
            return basis @ coefficients

    setup_seconds = perf_counter() - start

    def combined(residual: np.ndarray) -> np.ndarray:
        classical = base.apply(residual)
        remaining = residual - matrix @ classical
        return classical + coarse_action(remaining)

    action = InverseAction(
        f"{base.name}+{name}_q{basis.shape[1]}",
        combined,
        setup_seconds=base.setup_seconds + setup_seconds,
    )
    diagnostics = {
        "coarse_variant": variant,
        "coarse_dimension": int(basis.shape[1]),
        "symmetry_measure": symmetry,
        "coarse_setup_seconds": setup_seconds,
        "reduced_condition": reduced_condition,
        "basis_orthogonality_error": orthogonality_error,
    }
    return action, diagnostics
